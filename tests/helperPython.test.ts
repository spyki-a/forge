import { describe, expect, it } from 'vitest'
import {
  HELPER_PYTHON_MISSING,
  HELPER_RECEIPT_UNREADABLE,
  UNPARSEABLE_RECEIPT,
  receiptFromText,
  resolveHelperPython,
  type HelperPythonInput
} from '../src/shared/sidecar/helperPython'
import type { HelperPackManifest, PackPlatform, PackReceipt, PlatformPack } from '../src/shared/sidecar/pack'
import { helperPythonFor } from './integration/venv'

/*
 * Which interpreter runs the AI helper (docs/CLIPS.md §3a.2, §16.42 (b)).
 * Development: FORGE_PYTHON → .venv → the dev pack → python/python3.
 * Packaged: the pack → FORGE_PYTHON → absent, never a PATH Python. A receipt
 * that does not parse, or that matches with its interpreter gone, is damaged
 * and nothing is spawned.
 *
 * The manifest is built here by hand with fake hashes: packManifest.ts is
 * generated by scripts/pack_lock.py and is not this test's subject. Every
 * hash below differs from every other, so a receipt that differs from the
 * manifest in ONE field differs in that field only, and each of
 * receiptMatches' checks is the only thing between it and the pack rung.
 */

const hex = (c: string): string => c.repeat(64)

const MAC_INTERPRETER = hex('a')
const MAC_LOCK = hex('b')
const WIN_INTERPRETER = hex('c')
const WIN_LOCK = hex('d')
const OTHER = hex('e')

function platformPack(interpreterSha256: string, lockSha256: string, python: string): PlatformPack {
  return {
    interpreter: {
      name: 'cpython-3.14.8+20261001-install_only_stripped.tar.gz',
      url: 'https://github.com/astral-sh/python-build-standalone/releases/download/20261001/cpython.tar.gz',
      bytes: 1000,
      sha256: interpreterSha256
    },
    wheels: [
      {
        name: 'numpy-2.3.0-cp314-cp314-any.whl',
        url: 'https://files.pythonhosted.org/packages/00/00/numpy.whl',
        bytes: 10,
        sha256: hex('9')
      }
    ],
    lock: { file: 'pack/lock.txt', sha256: lockSha256 },
    python,
    expects: ['audio.beats'],
    bytesOnDisk: 0,
    longestPath: 0,
    longestDir: 0
  }
}

const MANIFEST: HelperPackManifest = {
  pack: 1,
  python: { version: '3.14.8', build: '20261001' },
  platforms: {
    'darwin-arm64': platformPack(MAC_INTERPRETER, MAC_LOCK, 'python/bin/python3.14'),
    'win32-x64': platformPack(WIN_INTERPRETER, WIN_LOCK, 'python/python.exe')
  }
}

function receipt(over: Partial<PackReceipt> = {}): PackReceipt {
  return {
    pack: 1,
    python: '3.14.8',
    build: '20261001',
    platform: 'darwin-arm64',
    interpreterSha256: MAC_INTERPRETER,
    lockSha256: MAC_LOCK,
    bytesOnDisk: 700_000_000,
    installedAt: '2026-10-14T12:00:00.000Z',
    appVersion: '0.1.0',
    hello: { capabilities: ['audio.beats'], degraded: {} },
    selftest: { beats: 'ok' },
    ...over
  }
}

const ROOT = '/Users/someone/Library/Application Support/Forge/python/1'
const PACK_PYTHON = `${ROOT}/python/bin/python3.14`
const VENV_PYTHON = '/repo/sidecar/.venv/bin/python'
const OWN_PYTHON = '/opt/someone/bin/python3.12'

/** A pack on disk whose receipt matches this build and whose interpreter is there. */
function macPack(over: Partial<NonNullable<HelperPythonInput['pack']>> = {}): HelperPythonInput['pack'] {
  return { receipt: receipt(), interpreterExists: true, python: PACK_PYTHON, root: ROOT, ...over }
}

function input(over: Partial<HelperPythonInput>): HelperPythonInput {
  return {
    packaged: false,
    env: {},
    platform: 'darwin',
    venvPython: null,
    pack: null,
    manifest: MANIFEST,
    packPlatform: 'darwin-arm64' satisfies PackPlatform,
    ...over
  }
}

const packaged = (over: Partial<HelperPythonInput>): HelperPythonInput => input({ packaged: true, ...over })

describe('development: FORGE_PYTHON, then .venv, then the dev pack, then PATH', () => {
  it('runs FORGE_PYTHON ahead of the venv and the dev pack', () => {
    const choice = resolveHelperPython(
      input({ env: { FORGE_PYTHON: OWN_PYTHON }, venvPython: VENV_PYTHON, pack: macPack() })
    )
    expect(choice).toEqual({ kind: 'env', python: OWN_PYTHON })
  })

  it('runs the venv ahead of the dev pack, so npm run dev never quietly runs a pack', () => {
    const choice = resolveHelperPython(input({ venvPython: VENV_PYTHON, pack: macPack() }))
    expect(choice).toEqual({ kind: 'venv', python: VENV_PYTHON })
  })

  it('runs the dev pack ahead of a PATH Python, with its own number and folder', () => {
    const choice = resolveHelperPython(input({ pack: macPack() }))
    expect(choice).toEqual({ kind: 'pack', python: PACK_PYTHON, pack: 1, root: ROOT })
  })

  it('falls back to python on win32 and python3 elsewhere', () => {
    expect(resolveHelperPython(input({ platform: 'win32', packPlatform: 'win32-x64' }))).toEqual({
      kind: 'path',
      python: 'python'
    })
    expect(resolveHelperPython(input({ platform: 'darwin' }))).toEqual({ kind: 'path', python: 'python3' })
    expect(resolveHelperPython(input({ platform: 'linux', packPlatform: { unsupported: 'linux' } }))).toEqual({
      kind: 'path',
      python: 'python3'
    })
  })

  it('reads an empty FORGE_PYTHON as unset, as the service always has', () => {
    const choice = resolveHelperPython(input({ env: { FORGE_PYTHON: '' }, venvPython: VENV_PYTHON }))
    expect(choice).toEqual({ kind: 'venv', python: VENV_PYTHON })
  })

  it('lets a damaged dev pack stop the PATH fallback after it, never the venv or FORGE_PYTHON before it', () => {
    const gone = macPack({ interpreterExists: false })
    expect(resolveHelperPython(input({ pack: gone }))).toEqual({ kind: 'damaged', reason: HELPER_PYTHON_MISSING })
    expect(resolveHelperPython(input({ pack: gone, venvPython: VENV_PYTHON })).kind).toBe('venv')
    expect(resolveHelperPython(input({ pack: gone, env: { FORGE_PYTHON: OWN_PYTHON } })).kind).toBe('env')
  })
})

describe('a packaged app: the pack, then FORGE_PYTHON, then nothing', () => {
  it('runs the pack ahead of FORGE_PYTHON', () => {
    const choice = resolveHelperPython(packaged({ env: { FORGE_PYTHON: OWN_PYTHON }, pack: macPack() }))
    expect(choice).toEqual({ kind: 'pack', python: PACK_PYTHON, pack: 1, root: ROOT })
  })

  it('runs FORGE_PYTHON when no pack is installed: the escape hatch', () => {
    expect(resolveHelperPython(packaged({ env: { FORGE_PYTHON: OWN_PYTHON } }))).toEqual({
      kind: 'env',
      python: OWN_PYTHON
    })
  })

  it('is absent with neither, on every platform, and never runs a PATH Python or a venv', () => {
    for (const [platform, packPlatform] of [
      ['darwin', 'darwin-arm64'],
      ['win32', 'win32-x64']
    ] as const) {
      expect(resolveHelperPython(packaged({ platform, packPlatform }))).toEqual({ kind: 'absent' })
      // A venv path handed to a packaged app is still not a rung there.
      expect(resolveHelperPython(packaged({ platform, packPlatform, venvPython: VENV_PYTHON }))).toEqual({
        kind: 'absent'
      })
    }
  })

  it('reads the escape hatch in any case on win32, as Windows does', () => {
    // `{ ...process.env }` on Windows keeps a `setx forge_python` in its own case.
    const choice = resolveHelperPython(
      packaged({ platform: 'win32', packPlatform: 'win32-x64', env: { Forge_Python: 'C:\\Py\\python.exe' } })
    )
    expect(choice).toEqual({ kind: 'env', python: 'C:\\Py\\python.exe' })
  })
})

describe('the receipt', () => {
  const notAPack: [string, Partial<PackReceipt>][] = [
    ['another platform', { platform: 'win32-x64' }],
    ['another lockSha256', { lockSha256: OTHER }],
    ['another interpreterSha256', { interpreterSha256: OTHER }]
  ]

  for (const [what, over] of notAPack) {
    it(`with ${what} is not a pack, and not damaged either: the order falls through`, () => {
      const pack = macPack({ receipt: receipt(over) })
      expect(resolveHelperPython(packaged({ pack }))).toEqual({ kind: 'absent' })
      expect(resolveHelperPython(packaged({ pack, env: { FORGE_PYTHON: OWN_PYTHON } }))).toEqual({
        kind: 'env',
        python: OWN_PYTHON
      })
      expect(resolveHelperPython(input({ pack }))).toEqual({ kind: 'path', python: 'python3' })
    })
  }

  it('that matches with its interpreter gone is damaged, never absent, and says what happened', () => {
    const choice = resolveHelperPython(packaged({ pack: macPack({ interpreterExists: false }) }))
    expect(choice).toEqual({ kind: 'damaged', reason: HELPER_PYTHON_MISSING })
    expect(HELPER_PYTHON_MISSING).toBe("Python is missing from the AI helper's folder (removed by antivirus?)")
  })

  it('that does not parse is damaged', () => {
    const torn = receiptFromText('{"pack": 1, "platform": "darw')
    expect(torn).toBe(UNPARSEABLE_RECEIPT)
    for (const value of [torn, receiptFromText(''), receiptFromText('null'), receiptFromText('{}'), 'pack.json']) {
      const choice = resolveHelperPython(packaged({ pack: macPack({ receipt: value }) }))
      expect(choice).toEqual({ kind: 'damaged', reason: HELPER_RECEIPT_UNREADABLE })
    }
  })

  it('reads a well-formed receipt’s text back to the receipt', () => {
    const text = JSON.stringify(receipt())
    expect(resolveHelperPython(packaged({ pack: macPack({ receipt: receiptFromText(text) }) })).kind).toBe('pack')
  })

  it('is never ignored silently: a damaged pack wins over FORGE_PYTHON in a packaged app', () => {
    const env = { FORGE_PYTHON: OWN_PYTHON }
    expect(resolveHelperPython(packaged({ env, pack: macPack({ interpreterExists: false }) }))).toEqual({
      kind: 'damaged',
      reason: HELPER_PYTHON_MISSING
    })
    expect(resolveHelperPython(packaged({ env, pack: macPack({ receipt: UNPARSEABLE_RECEIPT }) }))).toEqual({
      kind: 'damaged',
      reason: HELPER_RECEIPT_UNREADABLE
    })
  })

  it('from an older lock with its interpreter gone is an Update, not a Repair', () => {
    // Not this build's pack, so whether its files are there is not the question.
    const pack = macPack({ receipt: receipt({ lockSha256: OTHER }), interpreterExists: false })
    expect(resolveHelperPython(packaged({ pack }))).toEqual({ kind: 'absent' })
  })

  it('never names the code’s word for the process in what the row shows', () => {
    for (const reason of [HELPER_PYTHON_MISSING, HELPER_RECEIPT_UNREADABLE]) {
      expect(reason).not.toMatch(/sidecar/i)
      expect(reason).toMatch(/the AI helper/i)
    }
  })
})

describe('a machine with no pack for it', () => {
  // macOS 13: the OS answers darwin, the receipt is the Mac's and matches its
  // hashes, the interpreter is on disk. packPlatform still says no.
  const macos13 = {
    platform: 'darwin' as const,
    packPlatform: { unsupported: 'The AI helper needs macOS 14 or later' }
  }

  it('never picks a pack', () => {
    expect(resolveHelperPython(packaged({ ...macos13, pack: macPack() }))).toEqual({ kind: 'absent' })
    expect(resolveHelperPython(packaged({ ...macos13, pack: macPack(), env: { FORGE_PYTHON: OWN_PYTHON } }))).toEqual({
      kind: 'env',
      python: OWN_PYTHON
    })
    expect(resolveHelperPython(input({ ...macos13, pack: macPack() }))).toEqual({ kind: 'path', python: 'python3' })
  })

  it('reads no receipt as damaged, since Repair could not run there either', () => {
    const torn = macPack({ receipt: UNPARSEABLE_RECEIPT })
    expect(resolveHelperPython(packaged({ ...macos13, pack: torn }))).toEqual({ kind: 'absent' })
  })
})

describe("the Python-only tests' interpreter (tests/integration/venv.ts helperPythonFor)", () => {
  // sidecarMedia.int and oldestFfmpeg's helper-argv tests run on it; sidecar.int
  // starts the helper through devHelperLaunch. With no venv the two must fall
  // back to the same Python, or a Surface with python.org's python.exe (and no
  // python3.exe) and no FORGE_PYTHON runs one set and fails the other with 9009.
  it('falls back as the app’s development order does: python on win32, python3 elsewhere', () => {
    expect(helperPythonFor({ venvPython: null, env: {}, platform: 'win32' })).toBe('python')
    expect(helperPythonFor({ venvPython: null, env: {}, platform: 'darwin' })).toBe('python3')
    expect(helperPythonFor({ venvPython: null, env: {}, platform: 'win32' })).toBe(
      (resolveHelperPython(input({ platform: 'win32' })) as { python: string }).python
    )
  })

  it('takes FORGE_PYTHON as the app does (set and not empty, any case on win32), and the venv before it', () => {
    expect(helperPythonFor({ venvPython: null, env: { FORGE_PYTHON: '' }, platform: 'win32' })).toBe('python')
    expect(helperPythonFor({ venvPython: null, env: { Forge_Python: 'C:\\Py312\\python.exe' }, platform: 'win32' })).toBe('C:\\Py312\\python.exe')
    expect(helperPythonFor({ venvPython: null, env: { FORGE_PYTHON: '/opt/py/bin/python3' }, platform: 'darwin' })).toBe('/opt/py/bin/python3')
    expect(helperPythonFor({ venvPython: '/repo/sidecar/.venv/bin/python', env: { FORGE_PYTHON: '/opt/py' }, platform: 'darwin' })).toBe(
      '/repo/sidecar/.venv/bin/python'
    )
  })
})
