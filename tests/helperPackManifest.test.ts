/*
 * The AI helper's pack manifest (docs/CLIPS.md §3a.1, §3a.2, §3a.7):
 * HELPER_PACK, generated by scripts/pack_lock.py, against the committed locks,
 * sidecar/pack/history.json and pack.ts's own rules.
 *
 * Each check is a function returning its problems, so the same check that
 * passes on the committed files is also run on a scratch copy with the bug in
 * it (a dropped wheel, opencv in the lock, a `latest` URL, an edited lock, a
 * changed lock under an old number) and must name it. A check that cannot
 * fail on the scratch copy would pass the bug too.
 */

const ROOT = resolve(__dirname, '..')
const SIDECAR = join(ROOT, 'sidecar')
const PLATFORMS: PackPlatform[] = ['darwin-arm64', 'win32-x64']

const HEX64 = /^[0-9a-f]{64}$/
const PYPI_FILES = 'https://files.pythonhosted.org/packages/'
const PBS_RELEASES = 'https://github.com/astral-sh/python-build-standalone/releases/download/'

const canonical = (name: string): string => name.toLowerCase().replace(/[-_.]+/g, '-')

const sha256 = (data: Buffer | string): string => createHash('sha256').update(data).digest('hex')

function lockBytes(platform: PackPlatform, manifest: HelperPackManifest = HELPER_PACK): Buffer {
  return readFileSync(join(SIDECAR, manifest.platforms[platform].lock.file))
}

/** A deep copy to break: the committed manifest is never touched. */
function scratch(manifest: HelperPackManifest = HELPER_PACK): HelperPackManifest {
  return JSON.parse(JSON.stringify(manifest)) as HelperPackManifest
}

/* ------------------------------------------------------------- the checks */

function fileProblems(pack: PlatformPack): string[] {
  const problems: string[] = []
  for (const f of [pack.interpreter, ...pack.wheels]) {
    if (!HEX64.test(f.sha256)) problems.push(`${f.name}: sha256 ${f.sha256} is not 64 lower-case hex`)
    if (!Number.isInteger(f.bytes) || f.bytes <= 0) problems.push(`${f.name}: ${f.bytes} bytes`)
  }
  if (!HEX64.test(pack.lock.sha256)) problems.push(`the lock's sha256 ${pack.lock.sha256} is not 64 lower-case hex`)
  return problems
}

function urlProblems(manifest: HelperPackManifest, platform: PackPlatform): string[] {
  const pack = manifest.platforms[platform]
  const problems: string[] = []
  for (const w of pack.wheels) {
    if (!w.url.startsWith(PYPI_FILES)) problems.push(`${w.name}: ${w.url} is not on ${PYPI_FILES}`)
    // The URL's last segment is the file the lock names, not some other file.
    if (decodeURIComponent(w.url.split('/').pop() ?? '') !== w.name) problems.push(`${w.name}: ${w.url} is another file`)
  }
  const i = pack.interpreter
  const tag = manifest.python.build
  if (!/^\d{8}$/.test(tag)) problems.push(`the build ${tag} is not an exact release tag`)
  const exact = `${PBS_RELEASES}${tag}/${encodeURIComponent(i.name)}`
  if (i.url !== exact) problems.push(`the interpreter is at ${i.url}, not ${exact}`)
  if (/latest/i.test(i.url)) problems.push(`the interpreter URL ${i.url} names latest`)
  if (!i.name.startsWith(`cpython-${manifest.python.version}+${tag}-`)) problems.push(`${i.name} is not ${manifest.python.version}+${tag}`)
  if (!i.name.endsWith('-install_only_stripped.tar.gz')) problems.push(`${i.name} is not install_only_stripped`)
  return problems
}

/** Every `--hash=sha256:<hex>` in the lock, read with matchAll over every line. */
function lockHashes(text: string): string[] {
  return [...text.matchAll(/--hash=sha256:([0-9a-f]{64})/g)].map((m) => m[1])
}

/** The lock's hashes and the manifest's wheel hashes are one set, both ways, one each. */
function hashSetProblems(text: string, pack: PlatformPack): string[] {
  const problems: string[] = []
  const inLock = lockHashes(text)
  const anyHash = [...text.matchAll(/--hash=/g)].length
  if (anyHash !== inLock.length) problems.push(`${anyHash - inLock.length} --hash= not in sha256:<64 hex> form`)
  const lockSet = new Set(inLock)
  const wheelSet = new Set(pack.wheels.map((w) => w.sha256))
  if (lockSet.size !== inLock.length) problems.push('a hash appears twice in the lock')
  if (wheelSet.size !== pack.wheels.length) problems.push('a hash appears twice among the wheels')
  for (const h of lockSet) if (!wheelSet.has(h)) problems.push(`lock hash ${h} has no wheel in the manifest`)
  for (const h of wheelSet) if (!lockSet.has(h)) problems.push(`wheel hash ${h} is not in the lock`)
  return problems
}

/** The lock's bytes hash to the manifest's `lock.sha256`: the bytes pip is given are the bytes the pack was made from. */
function lockShaProblems(bytes: Buffer, pack: PlatformPack): string[] {
  const actual = sha256(bytes)
  return actual === pack.lock.sha256 ? [] : [`${pack.lock.file}: sha256 ${actual}, not the manifest's ${pack.lock.sha256}`]
}

/** Each lock line's name and version are the wheel's its hash names (wheel names normalise - to _). */
function lineToWheelProblems(text: string, pack: PlatformPack): string[] {
  const byHash = new Map(pack.wheels.map((w) => [w.sha256, w]))
  const problems: string[] = []
  for (const m of text.matchAll(/^([A-Za-z0-9][A-Za-z0-9._-]*)==(\S+) --hash=sha256:([0-9a-f]{64})$/gm)) {
    const wheel = byHash.get(m[3])
    if (!wheel) continue // hashSetProblems names it
    const [dist, version] = wheel.name.split('-')
    if (canonical(dist) !== canonical(m[1]) || version !== m[2]) {
      problems.push(`${m[1]}==${m[2]} hashes to ${wheel.name}`)
    }
  }
  return problems
}

/** The distributions a lock names, PEP 503 normal form. */
function lockNames(text: string): string[] {
  return [...text.matchAll(/^([A-Za-z0-9][A-Za-z0-9._-]*)==/gm)].map((m) => canonical(m[1]))
}

/** Each wheel's tags are the platform's: cp314, abi3 or py3; macOS arm64/universal2 at or under minOs; win_amd64. */
function wheelTagProblems(platform: PackPlatform, pack: PlatformPack): string[] {
  const problems: string[] = []
  const floor = (pack.minOs ?? '0.0').split('.').map(Number)
  for (const w of pack.wheels) {
    const parts = w.name.replace(/\.whl$/, '').split('-')
    const [py, abi, plat] = parts.slice(-3)
    const pyOk =
      (py === 'cp314' && abi === 'cp314') ||
      (abi === 'abi3' && /^cp3\d+$/.test(py) && Number(py.slice(3)) <= 14) ||
      (abi === 'none' && py.split('.').includes('py3'))
    if (!pyOk) problems.push(`${w.name}: ${py}-${abi} is not cp314`)
    const plats = plat.split('.')
    const platOk = plats.some((p) => {
      if (p === 'any') return true
      if (platform === 'win32-x64') return p === 'win_amd64'
      const mac = /^macosx_(\d+)_(\d+)_(arm64|universal2)$/.exec(p)
      if (!mac) return false
      const [major, minor] = [Number(mac[1]), Number(mac[2])]
      return major < floor[0] || (major === floor[0] && minor <= (floor[1] ?? 0))
    })
    if (!platOk) problems.push(`${w.name}: ${plat} is not ${platform}`)
  }
  return problems
}

/** resolved.json's per-target totals, written by pack_lock.py from the same files as the manifest. */
function readResolvedTargets(): Record<PackPlatform, { packBytes: number; wheelBytes: number }> {
  const resolved = JSON.parse(readFileSync(join(SIDECAR, 'pack', 'resolved.json'), 'utf8')) as {
    targets: Record<PackPlatform, { packBytes: number; wheelBytes: number }>
  }
  return resolved.targets
}

type History = Record<string, Record<string, { lockSha256: string; interpreterSha256: string }>>

function readHistory(): History {
  return JSON.parse(readFileSync(join(SIDECAR, 'pack', 'history.json'), 'utf8')) as History
}

function historyProblems(history: History, manifest: HelperPackManifest): string[] {
  const problems: string[] = []
  const numbers = Object.keys(history)
  for (const n of numbers) {
    if (!/^[1-9]\d*$/.test(n)) problems.push(`pack number ${n} is not a positive integer`)
    const pairs = history[n]
    const platforms = Object.keys(pairs).sort()
    if (platforms.join() !== [...PLATFORMS].sort().join()) problems.push(`pack ${n} names ${platforms.join(', ')}`)
    for (const p of platforms) {
      const pair = pairs[p]
      if (Object.keys(pair).sort().join() !== 'interpreterSha256,lockSha256') problems.push(`pack ${n} ${p} is not one pair`)
      if (!HEX64.test(pair.lockSha256) || !HEX64.test(pair.interpreterSha256)) problems.push(`pack ${n} ${p}: not 64 hex`)
    }
  }
  const seen = new Map<string, string>()
  for (const n of numbers) {
    const key = JSON.stringify(PLATFORMS.map((p) => history[n][p]))
    if (seen.has(key)) problems.push(`packs ${seen.get(key)} and ${n} carry the same hashes`)
    seen.set(key, n)
  }
  const current = history[String(manifest.pack)]
  if (!current) {
    problems.push(`pack ${manifest.pack} is not in history.json`)
    return problems
  }
  if (Math.max(...numbers.map(Number)) !== manifest.pack) problems.push(`pack ${manifest.pack} is not the newest number`)
  for (const p of PLATFORMS) {
    const want = {
      lockSha256: manifest.platforms[p].lock.sha256,
      interpreterSha256: manifest.platforms[p].interpreter.sha256
    }
    if (current[p]?.lockSha256 !== want.lockSha256) problems.push(`${p}: the lock changed under pack ${manifest.pack}`)
    if (current[p]?.interpreterSha256 !== want.interpreterSha256) {
      problems.push(`${p}: the interpreter changed under pack ${manifest.pack}`)
    }
  }
  return problems
}

