describe('HELPER_PACK: the files', () => {
  it.each(PLATFORMS)('%s: every file is a 64-hex lower-case sha256 with positive bytes', (platform) => {
    expect(fileProblems(HELPER_PACK.platforms[platform])).toEqual([])
    expect(HELPER_PACK.platforms[platform].wheels.length).toBeGreaterThan(40)
  })

  it('the check names an upper-case hash and a zero size (scratch copy)', () => {
    const bad = scratch()
    bad.platforms['darwin-arm64'].wheels[0].sha256 = bad.platforms['darwin-arm64'].wheels[0].sha256.toUpperCase()
    bad.platforms['darwin-arm64'].wheels[1].bytes = 0
    const problems = fileProblems(bad.platforms['darwin-arm64'])
    expect(problems).toHaveLength(2)
  })

  it.each(PLATFORMS)("%s: every wheel is PyPI's own file; the interpreter is on an exact tag, never latest", (platform) => {
    expect(urlProblems(HELPER_PACK, platform)).toEqual([])
    expect(HELPER_PACK.platforms[platform].interpreter.url).toContain(`/releases/download/${HELPER_PACK.python.build}/`)
  })

  it('the check names a latest URL and a wheel off PyPI (scratch copy)', () => {
    const bad = scratch()
    const i = bad.platforms['win32-x64'].interpreter
    // GitHub's own spelling of "the newest release", which is not a pin.
    i.url = `https://github.com/astral-sh/python-build-standalone/releases/latest/download/${encodeURIComponent(i.name)}`
    bad.platforms['win32-x64'].wheels[2].url = bad.platforms['win32-x64'].wheels[2].url.replace(
      'files.pythonhosted.org',
      'example.org'
    )
    const problems = urlProblems(bad, 'win32-x64')
    expect(problems.some((p) => p.includes('names latest'))).toBe(true)
    expect(problems.some((p) => p.includes('is not on https://files.pythonhosted.org/packages/'))).toBe(true)
    // and the macOS half of the same copy is untouched
    expect(urlProblems(bad, 'darwin-arm64')).toEqual([])
  })

  it.each(PLATFORMS)("%s: each wheel's tags are this platform's and cp314's", (platform) => {
    expect(wheelTagProblems(platform, HELPER_PACK.platforms[platform])).toEqual([])
  })

  it("the tag check names the other platform's wheel (scratch copy)", () => {
    const bad = scratch()
    const win = HELPER_PACK.platforms['win32-x64'].wheels.find((w) => w.name.endsWith('-win_amd64.whl'))
    expect(win).toBeDefined()
    bad.platforms['darwin-arm64'].wheels.push(win!)
    expect(wheelTagProblems('darwin-arm64', bad.platforms['darwin-arm64'])).toEqual([
      `${win!.name}: win_amd64 is not darwin-arm64`
    ])
  })

  it("the interpreter's names are the archives' own (row 26: python/bin/python3.14, python/python.exe)", () => {
    expect(HELPER_PACK.platforms['darwin-arm64'].python).toBe('python/bin/python3.14')
    expect(HELPER_PACK.platforms['win32-x64'].python).toBe('python/python.exe')
    expect(HELPER_PACK.platforms['darwin-arm64'].minOs).toBe('14.0')
  })
})

describe('HELPER_PACK: the locks', () => {
  it.each(PLATFORMS)("%s: the lock's hashes, every line, are the manifest's wheel hashes as a set, both ways", (platform) => {
    const text = lockBytes(platform).toString('utf8')
    const pack = HELPER_PACK.platforms[platform]
    expect(hashSetProblems(text, pack)).toEqual([])
    expect(lockHashes(text)).toHaveLength(pack.wheels.length)
    expect(lineToWheelProblems(text, pack)).toEqual([])
  })

  it('a wheel dropped from the manifest but kept in the lock fails the set (scratch copy)', () => {
    const text = lockBytes('darwin-arm64').toString('utf8')
    const bad = scratch()
    const dropped = bad.platforms['darwin-arm64'].wheels.splice(5, 1)[0]
    expect(hashSetProblems(text, bad.platforms['darwin-arm64'])).toEqual([
      `lock hash ${dropped.sha256} has no wheel in the manifest`
    ])
  })

  it('a line dropped from the lock but kept in the manifest fails the set the other way (scratch copy)', () => {
    const text = lockBytes('win32-x64').toString('utf8')
    const lines = [...text.matchAll(/^numpy==.*\n/gm)]
    expect(lines).toHaveLength(1)
    const cut = text.replace(lines[0][0], '')
    const numpy = HELPER_PACK.platforms['win32-x64'].wheels.find((w) => w.name.startsWith('numpy-'))
    expect(hashSetProblems(cut, HELPER_PACK.platforms['win32-x64'])).toEqual([
      `wheel hash ${numpy!.sha256} is not in the lock`
    ])
  })

  it.each(PLATFORMS)("%s: the lock file's sha256 is the manifest's", (platform) => {
    expect(lockShaProblems(lockBytes(platform), HELPER_PACK.platforms[platform])).toEqual([])
  })

  it('the lock edited without its sha256 is caught (scratch copy)', () => {
    const pack = HELPER_PACK.platforms['darwin-arm64']
    const edited = Buffer.concat([lockBytes('darwin-arm64'), Buffer.from('opencv-contrib-python==4.12.0.88\n')])
    const problems = lockShaProblems(edited, pack)
    expect(problems).toHaveLength(1)
    expect(problems[0]).toContain(`not the manifest's ${pack.lock.sha256}`)
    // and a manifest sha256 that names other bytes, with the lock untouched
    expect(lockShaProblems(lockBytes('darwin-arm64'), { ...pack, lock: { ...pack.lock, sha256: sha256('another lock\n') } })).toHaveLength(1)
  })

  it.each(PLATFORMS)('%s: the lock holds mediapipe and no opencv or matplotlib (the stub route)', (platform) => {
    const names = lockNames(lockBytes(platform).toString('utf8'))
    expect(names).toContain('mediapipe')
    expect(names.filter((n) => n.startsWith('opencv'))).toEqual([])
    expect(names).not.toContain('matplotlib')
  })

  it('opencv added to the lock is caught (scratch copy)', () => {
    const text = lockBytes('win32-x64').toString('utf8') + `opencv-contrib-python==4.12.0.88 --hash=sha256:${'0'.repeat(64)}\n`
    expect(lockNames(text).filter((n) => n.startsWith('opencv'))).toEqual(['opencv-contrib-python'])
  })

  it('the locks are ASCII and LF only, so their bytes are their sha256 on both platforms', () => {
    for (const platform of PLATFORMS) {
      const bytes = lockBytes(platform)
      expect([...bytes].every((b) => b < 0x80)).toBe(true)
      expect(bytes.includes(0x0d)).toBe(false)
    }
  })
})

