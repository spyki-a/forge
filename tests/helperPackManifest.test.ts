describe('the button: the files summed', () => {
  it.each(PLATFORMS)('%s: packBytes is the interpreter plus every wheel', (platform) => {
    const pack = HELPER_PACK.platforms[platform]
    let sum = pack.interpreter.bytes
    for (const w of pack.wheels) sum += w.bytes
    expect(packBytes(pack)).toBe(sum)
  })

  it.each(PLATFORMS)("%s: the button's number is resolved.json's packBytes, written as every button writes bytes", (platform) => {
    /*
     * The generator sums the same files into resolved.json's targets[p].packBytes.
     * For pack 1 that is 178,190,592 B, "170 MB", on the Mac and 215,104,551 B,
     * "205 MB", on Windows (CLIPS §3a.1). Those numbers are not pinned here: a
     * lock that rightly loses a wheel under --bump (hf-xet, §3a.8 row 35) would
     * fail a pin with nothing wrong.
     */
    const pack = HELPER_PACK.platforms[platform]
    const total = readResolvedTargets()[platform].packBytes
    expect(packBytes(pack)).toBe(total)
    expect(packSizeLabel(pack)).toBe(formatBytes(total))
    expect(packSizeLabel(pack)).toMatch(/^\d+ MB$/)
  })

  it.each(PLATFORMS)('%s: the hosts are GitHub, its asset host and PyPI’s files, each named', (platform) => {
    const hosts = packHosts(HELPER_PACK.platforms[platform])
    const allowed = ['files.pythonhosted.org', 'github.com', 'release-assets.githubusercontent.com']
    for (const host of allowed) expect(hosts).toContain(host)
    for (const host of hosts) expect(allowed).toContain(host)
  })
})

describe('packPlatform', () => {
  const mac = (osVersion: string, translated = false) =>
    packPlatform({ platform: 'darwin', arch: 'arm64', osVersion, translated })
  const win = (arch: string, translated: boolean) =>
    packPlatform({ platform: 'win32', arch, osVersion: '10.0.26100', translated })

  it("greys macOS 13 by getSystemVersion's 13.x, and takes 14, 15 and 26", () => {
    expect(mac('13.6.1')).toEqual({ unsupported: expect.stringMatching(/macOS 14/) })
    expect(mac('14.0')).toBe('darwin-arm64')
    expect(mac('15.7')).toBe('darwin-arm64')
    expect(mac('26.5.2')).toBe('darwin-arm64') // the dev Mac's getSystemVersion(), measured
  })

  it("never takes os.release()'s Darwin number for a supported Mac", () => {
    // Measured on the dev Mac (macOS 26.5.2): os.release() is '25.5.0'. A
    // caller that passed it would see every Mac from macOS 13 (Darwin 22.x)
    // to 26 (25.x) as supported, macOS 13 included, where the pack's
    // macosx_14_0 wheels cannot install. None of these is a marketing version.
    for (const darwin of ['22.6.0', '23.6.0', '24.6.0', '25.5.0']) {
      expect(mac(darwin), darwin).toEqual({ unsupported: expect.stringContaining(darwin) })
    }
  })

  it('reports Windows on Arm when translated is true on win32, and native arm64', () => {
    expect(win('x64', false)).toBe('win32-x64')
    // The x64 build emulated on an Arm machine: process.arch still says x64.
    expect(win('x64', true)).toEqual({ unsupported: expect.stringMatching(/Windows on Arm/) })
    expect(win('arm64', false)).toEqual({ unsupported: expect.stringMatching(/Windows on Arm/) })
  })

  it('a translated or Intel Mac and other systems are unsupported', () => {
    expect(isUnsupported(mac('26.5.2', true))).toBe(true)
    expect(isUnsupported(packPlatform({ platform: 'darwin', arch: 'x64', osVersion: '15.0', translated: false }))).toBe(
      true
    )
    expect(isUnsupported(packPlatform({ platform: 'linux', arch: 'x64', osVersion: '6.8.0', translated: false }))).toBe(
      true
    )
  })
})

describe('receiptMatches', () => {
  function receipt(platform: PackPlatform, over: Partial<PackReceipt> = {}): PackReceipt {
    const pack = HELPER_PACK.platforms[platform]
    return {
      pack: HELPER_PACK.pack,
      python: HELPER_PACK.python.version,
      build: HELPER_PACK.python.build,
      platform,
      interpreterSha256: pack.interpreter.sha256,
      lockSha256: pack.lock.sha256,
      bytesOnDisk: pack.bytesOnDisk,
      installedAt: '2026-10-14T00:00:00.000Z',
      appVersion: '0.1.0',
      hello: { capabilities: [...pack.expects], degraded: {} },
      selftest: {},
      ...over
    }
  }

  it.each(PLATFORMS)('%s: a receipt of this pack matches', (platform) => {
    expect(receiptMatches(receipt(platform), HELPER_PACK, platform)).toBe(true)
  })

  // Each failing receipt differs from a matching one in ONE field, so each of
  // receiptMatches' three checks is the only thing that refuses it.
  it("refuses a receipt for the other platform carrying this platform's hashes", () => {
    const r = receipt('darwin-arm64', { platform: 'win32-x64' })
    expect(receiptMatches(r, HELPER_PACK, 'darwin-arm64')).toBe(false)
  })

  it('refuses a receipt with another lockSha256', () => {
    const r = receipt('win32-x64', { lockSha256: HELPER_PACK.platforms['darwin-arm64'].lock.sha256 })
    expect(r.lockSha256).not.toBe(HELPER_PACK.platforms['win32-x64'].lock.sha256)
    expect(receiptMatches(r, HELPER_PACK, 'win32-x64')).toBe(false)
  })

  it('refuses a receipt with another interpreterSha256', () => {
    const r = receipt('darwin-arm64', {
      interpreterSha256: HELPER_PACK.platforms['win32-x64'].interpreter.sha256
    })
    expect(receiptMatches(r, HELPER_PACK, 'darwin-arm64')).toBe(false)
  })

  it('does not compare the pack number: it only names the folder', () => {
    expect(receiptMatches(receipt('win32-x64', { pack: HELPER_PACK.pack + 7 }), HELPER_PACK, 'win32-x64')).toBe(true)
  })

  it('refuses what is not a receipt', () => {
    expect(receiptMatches(null, HELPER_PACK, 'darwin-arm64')).toBe(false)
    expect(receiptMatches('{"pack":1}', HELPER_PACK, 'darwin-arm64')).toBe(false)
    expect(receiptMatches({ pack: 1, platform: 'darwin-arm64' }, HELPER_PACK, 'darwin-arm64')).toBe(false)
  })
})

describe('history.json: one pair of hashes per pack number', () => {
  it('each number carries one pair per platform, and the current number is the manifest’s pair', () => {
    const history = readHistory()
    expect(Object.keys(history)).toContain(String(HELPER_PACK.pack))
    expect(historyProblems(history, HELPER_PACK)).toEqual([])
  })

  it('a lock changed with the number kept is caught (scratch copy)', () => {
    // What a regenerated lock without --bump would give: a new lock sha256 in
    // the manifest under the same number history already holds.
    const bad = scratch()
    bad.platforms['win32-x64'].lock.sha256 = sha256('another lock\n')
    expect(historyProblems(readHistory(), bad)).toEqual([`win32-x64: the lock changed under pack ${HELPER_PACK.pack}`])
    // and the same change under the next number, recorded, is a pack
    bad.pack = HELPER_PACK.pack + 1
    const bumped: History = {
      ...readHistory(),
      [String(bad.pack)]: Object.fromEntries(
        PLATFORMS.map((p) => [
          p,
          { lockSha256: bad.platforms[p].lock.sha256, interpreterSha256: bad.platforms[p].interpreter.sha256 }
        ])
      )
    }
    expect(historyProblems(bumped, bad)).toEqual([])
  })

  it('an interpreter changed with the number kept, and a number with one platform, are caught (scratch copies)', () => {
    const bad = scratch()
    bad.platforms['darwin-arm64'].interpreter.sha256 = sha256('another interpreter')
    expect(historyProblems(readHistory(), bad)).toEqual([
      `darwin-arm64: the interpreter changed under pack ${HELPER_PACK.pack}`
    ])
    const history = readHistory()
    const onePlatform: History = { ...history, [String(HELPER_PACK.pack)]: { 'darwin-arm64': history[String(HELPER_PACK.pack)]['darwin-arm64'] } }
    expect(historyProblems(onePlatform, HELPER_PACK)).toContain(`pack ${HELPER_PACK.pack} names darwin-arm64`)
  })
})
