/**
 * The AI helper's Python pack — the pure half (docs/CLIPS.md §3a.1, §3a.2).
 *
 * The installers ship no Python. Instead the app installs one: a pinned
 * CPython from python-build-standalone (`install_only_stripped`), unpacked
 * under `userData/python/<pack>/`, with the base pack's wheels installed into
 * its own site-packages by its own pip, OFFLINE, from files the app fetched
 * itself and checked against the lock this build ships (`sidecar/pack/`).
 *
 * This file is types, the platform question and the receipt check: nothing
 * here touches the network, the disk or electron, so every rule is unit-tested
 * on its own. The manifest itself is `packManifest.ts`, generated by
 * `scripts/pack_lock.py` from PyPI's JSON and GitHub's per-asset digests, and
 * never written by hand. Which interpreter runs is `helperPython.ts`; the
 * install job is `src/main/sidecar/`.
 */

import { formatBytes } from '../assets/pack'

export type PackPlatform = 'darwin-arm64' | 'win32-x64'

/** One file the install fetches: the interpreter archive or a wheel. */
export interface PackFile {
  name: string
  url: string
  bytes: number
  /** hex, 64 characters, lower case */
  sha256: string
}

export interface PlatformPack {
  /**
   * github.com/astral-sh/python-build-standalone/releases/download/<tag>/…,
   * on an exact tag, never `latest`: the pin is the version.
   */
  interpreter: PackFile
  /** One per lock line, PyPI's own files.pythonhosted.org URL. */
  wheels: PackFile[]
  /** The lock file this platform installs from, relative to `sidecar/`, and its sha256. */
  lock: { file: string; sha256: string }
  /** The interpreter, relative to the version folder (`python/bin/python3.14`, `python/python.exe`). */
  python: string
  /**
   * What the self-test must see registered: asr.transcribe, audio.beats,
   * depth.layers, vision.measure, vision.faces, vision.facesModel,
   * vision.salient, vision.salientModel. Never a stems or voice method.
   */
  expects: string[]
  /** Measured by CI's install (§3a.8 row 28); 0 until it has. */
  bytesOnDisk: number
  /** The longest relative file path in the version folder, likewise. */
  longestPath: number
  /** The longest relative directory path, likewise. */
  longestDir: number
  /** '14.0' on darwin: onnxruntime and av publish arm64 wheels as macosx_14_0 only (§16.44). */
  minOs?: string
}

export interface HelperPackManifest {
  /** Names the folder; goes up whenever a lock or the interpreter changes. */
  pack: number
  python: { version: string; build: string }
  platforms: Record<PackPlatform, PlatformPack>
}

/**
 * `pack.json`, written LAST into the version folder and removed FIRST from it
 * (the asset packs' rule, src/main/assets/packs.ts): a folder with no receipt
 * is a partial, whatever else is in it.
 */
export interface PackReceipt {
  pack: number
  python: string
  build: string
  platform: PackPlatform
  interpreterSha256: string
  lockSha256: string
  bytesOnDisk: number
  installedAt: string
  appVersion: string
  /** What the helper registered when the install's hello came back. */
  hello: { capabilities: string[]; degraded: Record<string, string> }
  /** Per self-test group: 'ok', or its reason (§3a.3 stage 4). */
  selftest: Record<string, 'ok' | string>
}

export interface PlatformUnsupported {
  unsupported: string
}

/**
 * Which pack this machine takes — or why none does.
 *
 * `osVersion` is `process.getSystemVersion()`, the marketing version ('14.6.1'),
 * never `os.release()`'s Darwin number ('23.6.0'); the two differ by nine on
 * the Mac and a check written against the wrong one greys every Mac or none.
 * Measured on the dev Mac (Electron 44.3.0's main process, macOS 26.5.2):
 * `getSystemVersion()` '26.5.2', `os.release()` '25.5.0'. Read as a marketing
 * version, every Darwin number of a Mac that runs this app (22 for macOS 13
 * to 25 for macOS 26) would pass the floor, macOS 13's included. So a major of
 * 17 to 25 is refused as unreadable: macOS went from 15 to 26, no marketing
 * version is in that range, and a caller passing `os.release()` greys every
 * Mac from macOS 13 to 26 at once, the dev Mac first, instead of none. 16 is
 * left alone: it is not a Darwin number any Mac running Electron 44 has.
 * `translated` is `app.runningUnderARM64Translation`: Rosetta on the Mac (an
 * Intel build, which this app does not ship, so only a defence here), and on
 * Windows the x64 build running emulated on an Arm machine, where
 * `process.arch` still says 'x64' (§16.44).
 */
export function packPlatform(m: {
  platform: NodeJS.Platform
  arch: string
  osVersion: string
  translated: boolean
}): PackPlatform | PlatformUnsupported {
  if (m.platform === 'darwin') {
    if (m.arch !== 'arm64' || m.translated) {
      return { unsupported: 'The AI helper is not available on Intel Macs' }
    }
    const major = Number.parseInt(m.osVersion.split('.')[0] ?? '', 10)
    if (Number.isFinite(major) && major >= 17 && major <= 25) {
      return { unsupported: `The AI helper could not read this Mac's version (${m.osVersion})` }
    }
    if (!Number.isFinite(major) || major < 14) {
      return { unsupported: 'The AI helper needs macOS 14 or later' }
    }
    return 'darwin-arm64'
  }
  if (m.platform === 'win32') {
    if (m.translated || m.arch === 'arm64') {
      return { unsupported: 'The AI helper is not available on Windows on Arm yet' }
    }
    if (m.arch !== 'x64') {
      return { unsupported: `The AI helper is not available on ${m.arch} Windows` }
    }
    return 'win32-x64'
  }
  return { unsupported: `The AI helper is not available on ${m.platform}` }
}

export function isUnsupported(p: PackPlatform | PlatformUnsupported): p is PlatformUnsupported {
  return typeof p !== 'string'
}

/**
 * The receipt parsed, if it is one. Only the fields the checks read are
 * required to be there; a receipt from a build that wrote more is still a
 * receipt.
 */
export function parseReceipt(value: unknown): PackReceipt | null {
  if (!value || typeof value !== 'object') return null
  const r = value as Record<string, unknown>
  if (typeof r.pack !== 'number' || !Number.isInteger(r.pack)) return null
  if (typeof r.platform !== 'string') return null
  if (typeof r.interpreterSha256 !== 'string' || typeof r.lockSha256 !== 'string') return null
  if (typeof r.python !== 'string' || typeof r.build !== 'string') return null
  return r as unknown as PackReceipt
}

/**
 * True only when the receipt parses, its `platform` is this machine's, and its
 * `lockSha256` and `interpreterSha256` equal the manifest's for this platform.
 *
 * The `pack` number is NOT compared: it only names the folder. A lock or
 * interpreter change that ships without a bump still reads as not matching
 * (so, as "Update"), which is the safe direction; the bump itself is held by
 * `sidecar/pack/history.json` and its test.
 */
export function receiptMatches(
  receipt: unknown,
  manifest: HelperPackManifest,
  platform: PackPlatform
): boolean {
  const parsed = parseReceipt(receipt)
  if (!parsed) return false
  if (parsed.platform !== platform) return false
  const expected = manifest.platforms[platform]
  if (!expected) return false
  if (parsed.lockSha256 !== expected.lock.sha256) return false
  if (parsed.interpreterSha256 !== expected.interpreter.sha256) return false
  return true
}

/** Every byte an install of this platform's pack fetches: the interpreter and the wheels. */
export function packBytes(pack: PlatformPack): number {
  return pack.interpreter.bytes + pack.wheels.reduce((sum, w) => sum + w.bytes, 0)
}

/**
 * The size on the button, before any press (§0's click rule):
 * "Install the AI helper · 170 MB" on the Mac, "· 205 MB" on Windows.
 * MiB rounded, written "MB", as every other button in the app writes it.
 */
export function packSizeLabel(pack: PlatformPack): string {
  return formatBytes(packBytes(pack))
}

/** The hosts a restricted network must allow for the pack (§16.40), for the row and the guide. */
export function packHosts(pack: PlatformPack): string[] {
  const hosts = new Set<string>()
  for (const file of [pack.interpreter, ...pack.wheels]) {
    try {
      hosts.add(new URL(file.url).host)
    } catch {
      // A malformed URL is the manifest test's to catch, not the row's to hide.
    }
  }
  // GitHub answers the release URL with a redirect to this host (measured, §3a.1).
  if (hosts.has('github.com')) hosts.add('release-assets.githubusercontent.com')
  return [...hosts].sort()
}
