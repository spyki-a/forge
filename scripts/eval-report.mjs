#!/usr/bin/env node
/**
 * `npm run eval:report` — docs/EVAL.md from every run in eval/runs/.
 *
 * The runs are the record; this page is generated from them and never edited
 * by hand, so it cannot drift from what was measured. What a person concluded
 * goes in eval/findings.md, which is included verbatim at the top.
 */

import { readdirSync, readFileSync, writeFileSync, existsSync } from 'node:fs'
import { join, dirname } from 'node:path'
import { fileURLToPath } from 'node:url'

const REPO = join(dirname(fileURLToPath(import.meta.url)), '..')

const median = (xs) => {
  const v = xs.filter((x) => typeof x === 'number' && Number.isFinite(x)).sort((a, b) => a - b)
  if (v.length === 0) return null
  const m = Math.floor(v.length / 2)
  return v.length % 2 ? v[m] : (v[m - 1] + v[m]) / 2
}
const mean = (xs) => {
  const v = xs.filter((x) => typeof x === 'number' && Number.isFinite(x))
  return v.length === 0 ? null : v.reduce((a, b) => a + b, 0) / v.length
}
const fmt = (x, digits = 0) => (x === null || x === undefined ? '—' : Number(x).toFixed(digits))
const cell = (s) => String(s ?? '').replace(/\|/g, '\\|').replace(/\n/g, ' ')

/** The graphics pass's id (src/shared/director/schemaGraphics.ts `GRAPHICS_PASS`): its runs and results are not the spine's. */
export const GRAPHICS_PASS = 'graphics@1'

/** A run of the graphics eval (tests/eval/director.eval.test.ts, FORGE_EVAL_GRAPHICS), which has no spine row. */
export const isGraphicsRun = (run) => run?.pass === GRAPHICS_PASS

/**
 * The numbers one run comes down to. `options.pass` keeps the results of that
 * pass only; without it, every result but the graphics pass's (a spine
 * result carries `pass: 'spine@2'`, an older one none), so a graphics run is
 * never read as a broken spine row.
 */
export function summarise(run, options = {}) {
  const pass = options.pass ?? null
  const results = (run.results ?? []).filter((r) => (pass === null ? r.pass !== GRAPHICS_PASS : r.pass === pass))
  const count = (v) => results.filter((r) => r.verdict === v).length
  const headlines = results.flatMap((r) => r.headlines ?? [])
  const ratings = Object.values(run.ratings ?? {})
  const reasons = {}
  for (const r of ratings) for (const a of r.automatic ?? []) if (a.which === 'model') reasons[a.reason] = (reasons[a.reason] ?? 0) + 1
  return {
    briefs: results.length,
    used: count('used'),
    repaired: count('repaired'),
    rejected: count('rejected'),
    error: count('error'),
    /** The C0 bar counts a repaired plan as used: the plan landed, with notes. */
    landed: count('used') + count('repaired'),
    medianMs: median(results.map((r) => r.ms)),
    medianPrompt: median(results.map((r) => r.promptTokens)),
    medianOutput: median(results.map((r) => r.outputTokens)),
    headlines: headlines.length,
    headlinesFit: headlines.filter((h) => h.fits).length,
    copy: mean(ratings.map((r) => r.copy)),
    baselineCopy: mean(ratings.map((r) => r.baselineCopy)),
    rated: ratings.filter((r) => typeof r.copy === 'number').length,
    preferred: ratings.filter((r) => r.preferred === 'model').length,
    preferredOf: ratings.filter((r) => r.preferred).length,
    reasons
  }
}

/** Does a run meet C0's bar (docs/PLAN.md §3.4)? Null until it has been rated. */
export function meetsBar(summary) {
  if (summary.rated < summary.briefs || summary.briefs === 0) return null
  return summary.landed >= Math.ceil(0.8 * summary.briefs) && summary.copy !== null && summary.copy >= 3
}

export function buildReport(allRuns, findings = '') {
  const runs = allRuns.filter((run) => !isGraphicsRun(run))
  const graphicsRuns = allRuns.filter(isGraphicsRun)
  const lines = []
  lines.push('# The Director, measured')
  lines.push('')
  lines.push('> Generated by `npm run eval:report` from `eval/runs/*.json` — do not edit by hand.')
  lines.push('> What the plan is (`docs/PLAN.md` §3) and how to run it are there; what was concluded is')
  lines.push('> `eval/findings.md`, included below.')
  lines.push('')
  if (findings.trim()) {
    lines.push(findings.trim())
    lines.push('')
  }
  lines.push('## Runs')
  lines.push('')
  lines.push('| run | model | think | transport | landed | used · repaired · rejected · error | median s | median tokens in/out | headlines that fit | copy (model / standard) | preferred to standard | C0 bar |')
  lines.push('|---|---|---|---|---|---|---|---|---|---|---|---|')
  for (const run of runs) {
    const s = summarise(run)
    const bar = meetsBar(s)
    lines.push(
      `| ${cell(run.run)} | ${cell(run.model)} | ${run.think ? 'on' : 'off'} | ${run.transport} | ${s.landed}/${s.briefs} | ${s.used} · ${s.repaired} · ${s.rejected} · ${s.error} | ${fmt(s.medianMs === null ? null : s.medianMs / 1000, 1)} | ${fmt(s.medianPrompt)} / ${fmt(s.medianOutput)} | ${s.headlinesFit}/${s.headlines} | ${fmt(s.copy, 1)} / ${fmt(s.baselineCopy, 1)}${s.rated < s.briefs ? ` (${s.rated} rated)` : ''} | ${s.preferredOf ? `${s.preferred}/${s.preferredOf}` : '—'} | ${bar === null ? 'not rated' : bar ? '**met**' : 'not met'} |`
    )
  }
  lines.push('')
  for (const run of runs) {
    const s = summarise(run)
    lines.push(`## ${run.run}`)
    lines.push('')
    lines.push(`${run.provider} · \`${run.model}\` · think ${run.think ? 'on' : 'off'} · ${run.transport} · media ${run.media} · transitions ${run.catalogue?.builtIn ?? '?'} built-in + ${run.catalogue?.library ?? '?'} library`)
    lines.push('')
    if (Object.keys(s.reasons).length > 0) {
      lines.push(`"Looks automatic" on the model's ads, by reason: ${Object.entries(s.reasons).map(([k, v]) => `${k} ${v}`).join(' · ')}`)
      lines.push('')
    }
    lines.push('| brief | lang | verdict | s | tokens in/out | headlines (fit/written) | notes | reasoning |')
    lines.push('|---|---|---|---|---|---|---|---|')
    for (const r of run.results ?? []) {
      const hs = r.headlines ?? []
      const notes = r.verdict === 'rejected' || r.verdict === 'error' ? r.why : (r.problems ?? []).join('; ')
      lines.push(
        `| ${cell(r.fixtureId)} | ${cell(r.language)} | ${r.verdict} | ${fmt(r.ms / 1000, 1)} | ${fmt(r.promptTokens)} / ${fmt(r.outputTokens)} | ${hs.filter((h) => h.fits).length}/${hs.length} | ${cell(notes)} | ${cell(r.reasoning)} |`
      )
    }
    lines.push('')
    lines.push('<details><summary>Every headline</summary>')
    lines.push('')
    lines.push('| brief | role | headline | chars / fit in the shot |')
    lines.push('|---|---|---|---|')
    for (const r of run.results ?? []) {
      for (const h of r.headlines ?? []) {
        lines.push(`| ${cell(r.fixtureId)} | ${cell(h.role)} | ${cell(h.text)} | ${h.chars} / ${h.capacity}${h.fits ? '' : ' — **too long**'} |`)
      }
    }
    lines.push('')
    lines.push('</details>')
    lines.push('')
  }
  if (graphicsRuns.length > 0) lines.push(...graphicsReport(graphicsRuns))
  return `${lines.join('\n')}\n`
}

const pct = (x) => (x === null || x === undefined ? '—' : `${Math.round(x * 100)}%`)
const byKey = (m) => {
  const e = Object.entries(m ?? {})
  return e.length === 0 ? '—' : e.map(([k, v]) => `${k} ${v}`).join(' · ')
}

/**
 * A graphics run's blind template-fit ratings (`npm run eval:rate`), over the
 * EVAL set only: §6.12's bar is "template fit ≥ 3/5 on ≥ 8 of 10", the ten
 * eval transcripts, so a nested talk's rating (an older run's) is not counted.
 * `fixtures` is every result; `evalFixtures` the bar's denominator.
 */
export function summariseGraphics(run) {
  const evalIds = new Set((run.results ?? []).filter((r) => (r.set ?? 'eval') === 'eval').map((r) => r.fixtureId))
  const ratings = Object.entries(run.ratings ?? {})
    .filter(([id]) => evalIds.has(id))
    .map(([, r]) => r)
  return {
    fixtures: (run.results ?? []).length,
    evalFixtures: evalIds.size,
    rated: ratings.filter((r) => typeof r.fit === 'number').length,
    fit: mean(ratings.map((r) => r.fit)),
    baselineFit: mean(ratings.map((r) => r.baselineFit)),
    fitAtLeast3: ratings.filter((r) => typeof r.fit === 'number' && r.fit >= 3).length
  }
}

/** The figures of docs/CLIPS.md §6.10's "Recorded per run" for each graphics run, model against baseline, as score recorded them. */
export function graphicsReport(runs) {
  const lines = ['## Graphics runs', '']
  for (const run of runs) {
    const m = run.figures?.model ?? {}
    const b = run.figures?.baseline ?? {}
    const g = summariseGraphics(run)
    const both = (f) => `| ${f[0]} | ${f[1](m)} | ${f[2] ? f[2](b) : f[1](b)} |`
    lines.push(`### ${run.run}`)
    lines.push('')
    lines.push(`${run.provider} · \`${run.model}\` · ${run.transport} · ${g.fixtures} fixtures`)
    lines.push('')
    lines.push('| figure | model | baseline |')
    lines.push('|---|---|---|')
    const none = () => '—'
    for (const row of [
      ['windows', (f) => fmt(f.windows)],
      ['answered · parsed · cut off · wrong shape', (f) => `${fmt(f.answered)} · ${fmt(f.parsed)} · ${fmt(f.truncated)} · ${fmt(f.wrongShape)}`, none],
      ['prose came back (asked again) · retries not yet asked', (f) => `${fmt(f.prose)} · ${fmt(f.retryPending)}`, none],
      ['windows settled by the baseline instead', (f) => fmt(f.fellBack), none],
      ['answers that were HTTP errors, by status (the first)', (f) => `${byKey(f.errorsByStatus)}${f.firstError ? ` (${cell(f.firstError)})` : ''}`, none],
      ['graphics proposed', (f) => fmt(f.proposed)],
      ['proposed, by template', (f) => byKey(f.proposedByTemplate)],
      ['kept, by template', (f) => byKey(f.keptByTemplate)],
      ['dropped (share)', (f) => `${fmt(f.dropped)} (${pct(f.droppedShare)})`],
      ['dropped by the validator (share)', (f) => `${fmt(f.droppedByValidator)} (${pct(f.validatorShare)})`],
      ['dropped, by reason', (f) => byKey(f.droppedByReason)],
      ['**hallucination rate**', (f) => `**${fmt(f.hallucinations)}/${fmt(f.proposed)} (${pct(f.hallucinationRate)})**`],
      ['Hindi · Telugu dropped: a number said as a word (at most)', (f) => `${fmt(f.numberAsWord?.hi)} · ${fmt(f.numberAsWord?.te)}`],
      ['Telugu traps kept (negative endings missed, at most)', (f) => fmt(f.teluguTrapsKept)],
      ['traps kept', (f) => fmt(f.trapsKept)],
      ['lit repairs', (f) => fmt(f.litRepairs)],
      ['truth hits (±1 sentence)', (f) => `${fmt(f.truthHits)}/${fmt(f.truths)} (${pct(f.truthHitRate)}) · ${fmt(f.fixturesHit)} of ${fmt(f.fixturesWithTruth)} fixtures`],
      ['nested set, exact', (f) => ((f.nested ?? []).length === 0 ? '—' : f.nested.map((n) => `${cell(n.fixtureId)} ${n.exact ? 'exact' : 'not'} (${n.bar})`).join(' · '))],
      ['template fit, blind 1–5 (eval set)', () => `${fmt(g.fit, 1)} (≥ 3 on ${g.fitAtLeast3} of ${g.evalFixtures} eval fixtures; ${g.rated} rated)`, () => fmt(g.baselineFit, 1)]
    ]) {
      lines.push(both(row))
    }
    lines.push('')
  }
  return lines
}

export function loadRuns(dir = join(REPO, 'eval', 'runs')) {
  if (!existsSync(dir)) return []
  return readdirSync(dir)
    .filter((f) => f.endsWith('.json'))
    .sort()
    .map((f) => JSON.parse(readFileSync(join(dir, f), 'utf8')))
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const findingsFile = join(REPO, 'eval', 'findings.md')
  const findings = existsSync(findingsFile) ? readFileSync(findingsFile, 'utf8') : ''
  const runs = loadRuns()
  writeFileSync(join(REPO, 'docs', 'EVAL.md'), buildReport(runs, findings))
  console.log(`docs/EVAL.md — ${runs.length} run${runs.length === 1 ? '' : 's'}`)
}
